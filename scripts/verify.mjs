import { readFile } from 'node:fs/promises';
import { runInNewContext, Script } from 'node:vm';
import assert from 'node:assert/strict';

const html = await readFile(new URL('../src/index.html', import.meta.url), 'utf8');
const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)];
scripts.forEach((script) => new Script(script[1]));
const context = {};
runInNewContext(html.match(/<script id="calculation-core">([\s\S]*?)<\/script>/)[1], context);
const calc = context.PavementCalc;
const result = calc.solve(calc.DEFAULTS);
const concrete90 = calc.concreteProperties(24,calc.reliability(90,'supplied').z,'supplied');
assert.equal(concrete90.ps,10);
assert.ok(Math.abs(concrete90.meanPsi - 625.271) < .001);
assert.equal(calc.concreteProperties(24,-1.645,'supplied').ps,5);
assert.ok(Math.abs(calc.concreteProperties(24,calc.reliability(92.5,'supplied').z,'supplied').ps-7.5)<1e-10);
assert.throws(() => calc.concreteProperties(0,-1.405,'supplied'));
assert.throws(() => calc.concreteProperties(24,NaN,'supplied'));
assert.ok(Math.abs(calc.DEFAULTS.ecMillion-3.362957491)<1e-9);
const caseInputs={...calc.DEFAULTS};
delete caseInputs.fcMPa;
const legacy=calc.readCase({app:'aashto93-rigid-local',version:1,equationConstant:calc.CONSTANT,inputs:caseInputs});
assert.equal(legacy.fcMPa,24);
assert.throws(()=>calc.readCase({app:'aashto93-rigid-local',version:2,equationConstant:calc.CONSTANT,inputs:caseInputs}));
assert.ok(Math.abs(result.residual) < 1e-8);
assert.ok(result.roundedMm >= result.dMm);
assert.ok(calc.checkThickness(result.roundedMm, result).meets);
assert.equal(calc.reliability(92, 'supplied').z, -1.405);
assert.equal(calc.reliability(98, 'fhwa').z, -2.054);
assert.throws(() => calc.solve({ ...calc.DEFAULTS, wMillion: 0 }));
assert.throws(() => calc.solve({ ...calc.DEFAULTS, r: 100 }));
assert.throws(() => calc.solve({ ...calc.DEFAULTS, so: 1.01 }));
assert.equal(calc.validate({ ...calc.DEFAULTS, so: 1 }).length, 0);
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
assert.equal(ids.length, new Set(ids).size, 'IDs must be unique');
for (const link of html.matchAll(/href="#([^"]+)"/g)) assert.ok(ids.includes(link[1]), `Missing anchor ${link[1]}`);
for (const match of html.matchAll(/\$\('([^']+)'\)/g)) assert.ok(ids.includes(match[1]), `Missing interface element ${match[1]}`);
console.log(`Checks passed: script syntax, anchors, reliability, invalid inputs, convergence and capacity. Sample: ${result.dMm.toFixed(3)} mm → ${result.roundedMm} mm.`);
