import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
const root=new URL('../src/components/project-details/',import.meta.url);
const context={};runInNewContext(await readFile(new URL('engine.js',root),'utf8'),context);
const E=context.RoadInventory,data=JSON.parse(await readFile(new URL('network-data.json',root),'utf8')),inventory=E.load(data);
assert.equal(inventory.records.length,4573);assert.equal(inventory.columns.length,22);assert.match(inventory.sourceSha256,/^[a-f0-9]{64}$/);
const first=E.search(inventory.records,{query:'s00865lz'});assert.equal(first.length,1);assert.equal(first[0].raw.ROAD_SEC_CLASS,'Tertiary');assert.equal(first[0].raw.SEC_LENGTH,'7162');assert.equal(first[0].raw.PROVINCE,'Nueva Vizcaya');assert.equal(first[0].raw.ROAD_NAME,'Pantabangan-Canili-Basal-Baler Rd');
assert.equal(E.search(inventory.records,{query:'s05060lz'}).length,2,'Do not merge duplicate section IDs');
assert.equal(E.search(inventory.records,{query:'definitely nonexistent road 12345'}).length,0);
assert.equal(E.search(inventory.records,{query:'S00865LZ',PROVINCE:'Aurora'}).length,0,'Respect location filters');
assert.equal(E.search(inventory.records,{ROAD_SEC_CLASS:'Primary'}).length,734);
assert.equal(E.search(inventory.records,{ROAD_SEC_CLASS:'Secondary'}).length,1637);
assert.equal(E.search(inventory.records,{ROAD_SEC_CLASS:'Tertiary'}).length,2202);
assert.equal(E.search(inventory.records,{query:'Pantabangan Nueva Vizcaya'}).some(row=>row.raw.SECTION_ID==='S00865LZ'),true);
assert.equal(E.options(inventory.records,'PROVINCE').includes('Nueva Vizcaya'),true);
const exported=E.csv(['a','b'],{a:'Road, name',b:'a"b'});assert.equal(exported,'"Road, name","a""b"');
assert.throws(()=>E.load({...data,recordCount:1}));
const broken=JSON.parse(JSON.stringify(data));broken.rows[0][0]=-1;assert.throws(()=>E.load(broken));
assert.equal(inventory.records[0].raw.Shape,'','Do not invent geometry');
assert.equal(Object.values(inventory.records[0].raw).every(value=>typeof value==='string'),true);
console.log('Road inventory: all 4,573 records decoded; identifiers, classifications, duplicate IDs, combined filters, blanks and CSV escaping verified.');
